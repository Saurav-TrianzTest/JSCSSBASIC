/**
 * scripts/extract-critical.js
 *
 * CLOUD READINESS FIX (cr-css-1002): Critical CSS extraction build script.
 *
 * Extracts the above-fold critical CSS from index.html + site.css using the
 * `critical` npm package and writes the result to assets/css/critical.css.
 *
 * This script is run during CI/CD before deploying to AWS:
 *   npm run extract-critical
 *
 * After running this script:
 *   1. Upload assets/css/critical.css to S3:
 *        aws s3 cp assets/css/critical.css \
 *            s3://${S3_BUCKET}/assets/css/critical.css \
 *            --cache-control "max-age=86400"
 *   2. Invalidate the CloudFront cache for the critical CSS object:
 *        aws cloudfront create-invalidation \
 *            --distribution-id ${CF_DIST_ID} \
 *            --paths "/assets/css/critical.css"
 *
 * The Lambda@Edge function (lambda-edge/critical-css-injector.js) will pick up
 * the new critical CSS on its next cache refresh (TTL: 5 minutes).
 */

import { generate } from 'critical';
import { writeFileSync } from 'fs';
import { resolve, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const projectRoot = resolve(__dirname, '..');

async function extractCritical() {
  console.log('[extract-critical] Extracting above-fold critical CSS...');

  const result = await generate({
    base: projectRoot,
    src: 'index.html',
    css: ['assets/css/site.css', 'assets/css/brand.css'],
    // Viewport dimensions covering common above-fold breakpoints
    dimensions: [
      { width: 375,  height: 812  }, // Mobile (iPhone 12)
      { width: 768,  height: 1024 }, // Tablet
      { width: 1280, height: 800  }, // Desktop
      { width: 1920, height: 1080 }, // Large desktop
    ],
    inline: false,   // We handle inlining via Lambda@Edge — just extract the CSS
    extract: false,
    rebase: false,
  });

  const outputPath = resolve(projectRoot, 'assets/css/critical.css');
  const header = [
    '/*',
    ' * critical.css — Pre-extracted above-fold critical CSS bundle',
    ' * Generated by: npm run extract-critical',
    ' * Generated at: ' + new Date().toISOString(),
    ' *',
    ' * CLOUD READINESS FIX (cr-css-1002): Inlined by Lambda@Edge at CloudFront edge.',
    ' * DO NOT edit manually — this file is overwritten by the build step.',
    ' */',
    '',
  ].join('\n');

  writeFileSync(outputPath, header + result.css, 'utf-8');

  console.log('[extract-critical] Written to: ' + outputPath);
  console.log('[extract-critical] Size: ' + Buffer.byteLength(result.css, 'utf-8') + ' bytes');
  console.log('[extract-critical] Done. Upload to S3 and invalidate CloudFront cache.');
}

extractCritical().catch((err) => {
  console.error('[extract-critical] ERROR:', err.message);
  process.exit(1);
});
